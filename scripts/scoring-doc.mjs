// Renders the factor and band tables in SCORING.md from src/policy/default-policy.json.
//   npm run docs:scoring   -> rewrites the tables in place
// tests/docs.test.ts fails if SCORING.md and the policy drift apart.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SECTION_NAME = {
  Likelihood: "Likelihood (points)",
  Impact: "Impact (points)",
  Preference: "Organization preferences (multiplier)",
  Mitigation: "Mitigations (score reduction)",
};

const pts = (section, p) =>
  section === "Preference" ? `+${p}×` : section === "Mitigation" ? (p ? `−${Math.round(p * 100)}%` : "0") : String(p);

const cite = (r) => `[${r.source}${r.id ? ` ${r.id}` : ""}](${r.url})`;

export function renderTables(policy) {
  const out = [];
  for (const section of Object.keys(SECTION_NAME)) {
    const fs = policy.factors.filter((f) => f.section === section);
    if (!fs.length) continue;
    out.push(`#### ${SECTION_NAME[section]}`, "");
    out.push("| ID | Factor | Answers | Required | Basis |", "|---|---|---|---|---|");
    for (const f of fs) {
      const answers = f.options.map((o) => `${o.label} = ${pts(section, o.points)}`).join("; ");
      const basis = f.basis === "preference" ? `**Org preference**${f.references.length ? `; related: ${f.references.map(cite).join(", ")}` : ""}` : f.references.map(cite).join(", ");
      out.push(`| ${f.id} | ${f.factor} | ${answers} | ${f.required ? "Yes" : "No"} | ${basis} |`);
    }
    out.push("");
  }
  out.push("#### Risk bands", "");
  out.push("| Band | Score at least | Decision | Re-review |", "|---|---|---|---|");
  for (const b of policy.bands) out.push(`| ${b.name} | ${b.scoreMin} | ${b.decision} | every ${b.reReviewMonths} months |`);
  out.push("");
  out.push(
    `Mitigation credit is capped at **${Math.round(policy.maxMitigationCredit * 100)}%**. ` +
      `The preference multiplier starts at **${policy.basePreferenceMultiplier}**. ` +
      (policy.mitigationsMakeConditional
        ? "If any mitigation is credited and the band says Approved, the decision becomes **Approved with Conditions**."
        : ""),
  );
  return out.join("\n");
}

const START = "<!-- tables:start (generated by `npm run docs:scoring`; don't edit by hand) -->";
const END = "<!-- tables:end -->";

export function replaceTables(doc, tables) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < 0) throw new Error("SCORING.md is missing the tables markers");
  return `${doc.slice(0, a + START.length)}\n\n${tables}\n\n${doc.slice(b)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("..", import.meta.url);
  const policy = JSON.parse(readFileSync(new URL("src/policy/default-policy.json", root), "utf8"));
  const docPath = new URL("SCORING.md", root);
  writeFileSync(docPath, replaceTables(readFileSync(docPath, "utf8"), renderTables(policy)));
  console.log("SCORING.md tables updated");
}
